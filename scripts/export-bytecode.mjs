import fs from "node:fs";

const names = ["ShepherdAccount", "ShepherdPolicy", "ShepherdVault"];
const out = {};
for (const name of names) {
  const file = `contracts/out/${name}.sol/${name}.json`;
  const json = JSON.parse(fs.readFileSync(file, "utf8"));
  out[name] = json.bytecode.object;
}

const body = `/** Generated by scripts/export-bytecode.mjs. Do not edit. */
export const bytecode = ${JSON.stringify(out, null, 2)} as {
  ShepherdAccount: string;
  ShepherdPolicy: string;
  ShepherdVault: string;
};
`;
fs.writeFileSync("packages/core/src/bytecode.ts", body);
console.log("wrote packages/core/src/bytecode.ts");
